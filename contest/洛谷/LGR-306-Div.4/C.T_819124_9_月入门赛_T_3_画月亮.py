import sys
input = sys.stdin.readline
n, r = map(int, input().split())
center = n // 2

for i in range(n):
    ans = []
    for j in range(n):
        if (i - center) ** 2 + (j - center) ** 2 <= r ** 2:
            ans.append("#")
        else:
            ans.append(".")
    print("".join(ans))