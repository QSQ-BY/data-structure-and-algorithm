#include <iostream>
using namespace std;

using ll = long long;
ll n, m, l, r;

//检查能否满足每个货架最多放置k个货物
bool check(ll k) {
    if (m * k < n) return false;

    ll q = n / k;
    ll t = n % k;

    ll minCost = k * q * (q + 1) / 2 + t * (q + 1);
    ll maxCost = (m + 1) * n - minCost;

    return minCost <= r && maxCost >= l;
}

int main() {
    cin >> n >> m >> l >> r;

    if (!check(n)) {
        cout << -1 << '\n';
        return 0;
    }

    ll left = (n + m - 1) / m;
    ll right = n;
    //01二分模型
    while (left < right) {
        ll mid = left + (right - left) / 2;

        if (check(mid))
            right = mid;
        else
            left = mid + 1;
    }

    cout << left << '\n';
    return 0;
}