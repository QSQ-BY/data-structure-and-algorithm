import sys
input = sys.stdin.buffer.readline
sys.setrecursionlimit(10**6)

chenga = 0

n = int(input())
s = list(map(int, input().split()))
t = list(map(int, input().split()))

graph = [[] for _ in range(n)]

for _ in range(n - 1):
    u, v, c = map(int, input().split())
    u -= 1
    v -= 1
    graph[u].append((v, c))
    graph[v].append((u, c))

ans = 0

def dfs(cur, fa):
    global ans
    # 当前节点自己的盈亏
    total = s[cur] - t[cur]

    for v, c in graph[cur]:
        if v == fa:
            continue

        # child 表示 v 子树整体的盈亏
        child = dfs(v, cur)

        # v 子树与外界只能通过 (u,v) 这条边
        # 因此必须搬运 abs(child) 个月饼
        ans += (abs(child) + c - 1) // c#向上取整

        # 把子树盈亏合并到当前子树
        total += child

    return total
dfs(0, -1)
print(ans)