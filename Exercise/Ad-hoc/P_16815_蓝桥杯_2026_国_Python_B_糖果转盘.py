import sys
input = sys.stdin.buffer.readline
def read():
    return map(int,input().split())
n = int(input())
string = list(input().decode().strip())
ans1 = 0
ans2 = 1
ans3  = n
bad = 0
for i,cur in enumerate(string):
    if(i == n-1):
        next = string[0]
    else:
        next = string[i+1]
    if(next == cur):
        bad += 1
if(bad == 0):
    print(ans3)
elif(bad == 1):
    print(ans2)
elif(bad > 1):
    print(ans1)