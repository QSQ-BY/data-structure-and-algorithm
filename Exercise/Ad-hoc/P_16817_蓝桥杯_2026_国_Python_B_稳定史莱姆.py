import sys
input = sys.stdin.buffer.readline
def solve():
    n = int(input())
    # depth[x]：这一组最多需要除以 3 多少次
    depth = {}
    for x in map(int, input().split()):
        k = 0
        while x % 3 == 0:
            x //= 3
            k += 1
        if k > depth.get(x, 0):
            depth[x] = k
    print(sum(depth.values()))
solve()
