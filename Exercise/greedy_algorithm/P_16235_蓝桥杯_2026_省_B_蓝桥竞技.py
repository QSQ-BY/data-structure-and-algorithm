#假设有n种类别，每种的数量是a1,a2,a3.....an，总数量为s
#我们要把他分为每组p人的队伍，想要完全分组没有剩余必须
#同时满足两个条件：
#1.S%P == 0,即S一定被P整除
#2.任何一个类别的数量ai都不能超过s/p
#即队伍里最大的数量不能超过s/p
import sys

def solve():
    input = sys.stdin.buffer.readline
    
    # 读取测试用例组数 T
    line = input()
    if not line:
        return
    t = int(line)
    
    out = []
    for _ in range(t):
        n = int(input())
        arr = list(map(int, input().split()))
        
        s = sum(arr)
        
        # 1. 总人数必须是 5 的倍数
        if s % 5 != 0:
            out.append("F")
            continue
        
        # 2. 如果总人数为 0，相当于组成 0 支战队，可行
        if s == 0:
            out.append("T")
            continue
            
        k = s // 5  # 战队数量
        m = max(arr) if arr else 0
        
        # 3. 任何位置的人数不能超过战队总数 k
        if m > k:
            out.append("F")
        else:
            out.append("T")
            
    print('\n'.join(out))

if __name__ == '__main__':
    solve()