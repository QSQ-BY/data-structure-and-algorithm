import sys
input = sys.stdin.buffer.readline
def read():
    return map(int,input().split())

n = int(input())
a = list(read())
b = list(read())
a.sort()
b.sort()

cnt = [0] * n           # cnt[d]：增加 d 次的元素有几个
stack = []
i = 0                  # 下一个尚未加入栈的 a
t = a[0]               # 当前尝试占用的最终位置

for _ in range(n):
    if not stack:       # 没有待安排元素，跳到下一个 a
        t = max(t, a[i])

    while i < n and a[i] <= t:
        stack.append(a[i])
        i += 1

    d = t - stack.pop()  # 栈顶是可用元素中原值最大的
    cnt[d] += 1
    t += 1

ans = 0
j = 0
for d in range(n - 1, -1, -1):
    for _ in range(cnt[d]):
        ans += d * b[j]  # b 已升序：大的 d 配小的 b
        j += 1

print(ans % (1 << 64))