""" 题目描述
小 A 穿上了一双神奇的弹跳鞋，他可以给弹跳鞋充能 x 点能量并启动，然后弹跳鞋会连续弹跳 x 次，过程中无法停止。

其中，第 i 次弹跳时小 A 可以跳跃的距离恰好为 x−i+1。

小 A 正站在一条路上，他希望跳到距离自己 L 的位置，你可以认为小 A 只能向正反两个方向跳跃，不需要考虑路的宽度。

小 A 想知道，如果他只给鞋子充能一次，他在所有弹跳完成后能否停在目标位置。如果能，输出最低需要多少能量；如果不能，输出 −1。

输入格式
输入包含一行一个整数，L。

输出格式
输出一行一个整数表示答案。

输入输出样例
输入 #1复制

4
输出 #1复制

3
说明/提示
【评测用例规模与约定】

对于 40% 的评测用例，L≤100。

对于 60% 的评测用例，L≤5000。

对于 100% 的评测用例，1≤L≤10 
18
 。 """
from math import isqrt
n = int(input())
k = (isqrt(8 * n + 1) - 1) // 2
while k * (k + 1) // 2 < n:
    k += 1

#只要最后S-L的距离是偶数那就可以到达
#每次选择一个距离进行撤回的时候，相较于原来的距离最后都是相差2*本次选择的距离，
#所以最后相差的距离一定要是偶数才能进行回撤
while (k * (k + 1) // 2 - n) % 2:
    k += 1
print(k)