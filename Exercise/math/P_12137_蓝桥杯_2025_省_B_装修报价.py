#对于几段固定的异或值，之间用加号减号进行链接
#在所有可能的链接之中，最后把他们加起来最后一定会加减抵消
#最后只剩下最前面的异或，后面的所i有异或值在加减枚举之中都会抵消
#只有最前面的连续异或值是一直不变的
#所以队友每一种前缀异或，只需要把他的异或值乘以所有的情况总数
#最后就能得到以该前缀作为开头的所有表达式的和
#方案种数的计算上，前缀的下一位一共只有加减两个选择
#后面的所有n-k-1个位置都有加减异或三种可能的选择
#所以最后的贡献总和就是prefix[k]*2*3**(n-k-1)
import sys
input = sys.stdin.buffer.readline
def read():
    return map(int,input().split())
n = int(input())
arr = list(read())
MOD = 10**9 + 7

# prefix[i]：前 i 个数的异或值
prefix = [0] * (n + 1)
for i in range(1, n + 1):
    prefix[i] = prefix[i - 1] ^ arr[i - 1]
# 全部使用异或的情况
ans = prefix[n]

for k in range(1, n):
    ans = (
        ans + 2 * pow(3, n - k - 1, MOD) * prefix[k]
    ) % MOD

print(ans)

