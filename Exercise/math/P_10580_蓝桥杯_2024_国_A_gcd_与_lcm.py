import sys
input = sys.stdin.buffer.readline
from math import factorial,comb
def read():
    return map(int,input().split())
t = int(input())
MOD = 998244353
for _ in range(t):
    #最大公约数，最小公倍数，数字的个数n
    x,y,n = read() 
    m = y//x
    ans = 1
    #gcd 中某个质因子的指数，
    #等于所有数中该质因子指数的最小值；
    #lcm 中的指数，等于最大值。
    #如果m中某个质因子的指数为e，就要统计：
    #长度为n，每项从 0,1，.....,e 中选，
    #并且同时出现过 0 和 e 的指数序列数量。
    #不加限制每种有(e+1)**n
    #没有出现0和没有出现过e都是e**n
    p = 2
    while p * p <= m:
        e = 0
        if(m%p != 0):
            p+= 1
            continue
        while m % p == 0:
            m //= p
            e += 1

        if e:
            ways = (
                pow(e + 1, n, MOD)
                - 2 * pow(e, n, MOD)
                + pow(e - 1, n, MOD)
            ) % MOD
            ans = ans * ways % MOD

        p += 1

    # 剩下的质因子指数一定为 1
    #如果指数是1的话，就只能是0或者1，最后2**n减去全是0和全是1的两种情况
    if m > 1:
        ans = ans * (pow(2, n, MOD) - 2) % MOD

    print(ans)

