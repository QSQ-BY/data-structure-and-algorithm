#使用循环数组进行空间优化
def solution2():
    n = 20260606
    MOD = 998244353
    k = 2026
    # f[i] 表示长度为 i、不含连续 k 个相同字母的串数。
    # 循环数组 dp[i % k] 保存 f[i]，只保留最近 k 项。
    dp = [0] * k
    dp[0] = 1
    for i in range(1, k):
        dp[i] = 26 * dp[i-1] % MOD

    prev = (26 * dp[k-1] - 26) % MOD  # f[k]
    dp[0] = prev
    for i in range(k+1, n+1):
        pos = i % k
        # 覆盖前 dp[pos] 是 f[i-k]，prev 是 f[i-1]。
        prev = (26 * prev - 25 * dp[pos]) % MOD
        dp[pos] = prev

    ans = (pow(26, n, MOD) - prev) % MOD
    print(ans)

