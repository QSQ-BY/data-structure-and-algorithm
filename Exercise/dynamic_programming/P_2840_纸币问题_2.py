import sys
input = sys.stdin.buffer.readline

def read():
    return map(int, input().split())

n, target = read()
money = list(read())

MOD = 10**9 + 7

# dp[j] 表示凑出 j 元的不同支付序列数量
dp = [0] * (target + 1)
dp[0] = 1

for j in range(1, target + 1):
    for cur in money:
        if cur <= j:
            dp[j] += dp[j-cur]
    dp[j] %= MOD

print(dp[target])
