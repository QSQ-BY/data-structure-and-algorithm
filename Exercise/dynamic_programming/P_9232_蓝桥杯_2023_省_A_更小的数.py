import sys

input = sys.stdin.buffer.readline

s = input().decode().strip()
n = len(s)

# 二维数组，每个元素只需要存 0 或 1
#dp[i][j]表示翻转[i,j]后能不能使得数字变小
dp = [bytearray(n) for _ in range(n)]
ans = 0
for length in range(2,n+1):
    #length表示数组的长度，i表示右端点
    for j in range(length-1,n):
        i = j - length + 1 
        if s[i] > s[j]:
            dp[i][j] = 1
        elif s[i] < s[j]:
            dp[i][j] = 0
        else:
            dp[i][j] = dp[i + 1][j - 1]
        ans += dp[i][j]
print(ans)