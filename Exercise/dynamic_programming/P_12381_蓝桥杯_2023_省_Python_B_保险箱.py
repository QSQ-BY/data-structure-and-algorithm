""" 题目描述
小蓝有一个保险箱，保险箱上共有 n 位数字。

小蓝可以任意调整保险箱上的每个数字，每一次操作可以将其中一位增加 1 或减少 1。

当某位原本为 9 或 0 时可能会向前（左边）进位/退位，当最高位（左边第一位）上的数字变化时向前的进位或退位忽略。

例如：

00000 的第 5 位减 1 变为 99999；
99999 的第 5 位减 1 变为 99998；
00000 的第 4 位减 1 变为 99990；
97993 的第 4 位加 1 变为 98003；
99909 的第 3 位加 1 变为 00009。
保险箱上一开始有一个数字 x，小蓝希望把它变成 y，这样才能打开它，问小蓝最少需要操作的次数。

输入格式
输入的第一行包含一个整数 n。

第二行包含一个 n 位整数 x。

第三行包含一个 n 位整数 y。

输出格式
输出一行包含一个整数表示答案。

输入输出样例
输入 #1复制

5
12349
54321
输出 #1复制

11
说明/提示
评测用例规模与约定
对于 30% 的评测用例，1≤n≤300；
对于 60% 的评测用例，1≤n≤3000；
对于所有评测用例，1≤n≤10 
5
 ，x,y 中仅包含数字 0 至 9，可能有前导零。 """
import sys
input = sys.stdin.buffer.readline

n = int(input())
a = input().strip()
b = input().strip()

INF = float("inf")

# dp[i][j] 表示处理完右边 i 位
# 并向高位传递进位 j-1 的最少操作次数
dp = [[INF] * 3 for _ in range(2)]
# 初始状态：未处理任何位，没有进位
dp[0][1] = 0
# 从右往左处理
for i in range(1, n + 1):
    cur = i%2
    pre = 1 - cur
    x = a[n - i] - 48
    y = b[n - i] - 48
    dp[cur] = [INF] * 3
    # 枚举上一位传来的进位
    for c in (-1, 0, 1):
        # 枚举当前位向高位产生的进位
        for k in (-1, 0, 1):
            cost = abs(y + 10 * k - x - c)
            dp[cur][k + 1] = min(
                dp[cur][k + 1],
                dp[pre][c + 1] + cost
            )
# 最高位的进位或退位忽略
print(min(dp[n%2]))