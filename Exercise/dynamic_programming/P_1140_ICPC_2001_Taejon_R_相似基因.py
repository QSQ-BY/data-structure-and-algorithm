import sys
input = sys.stdin.buffer.readline

n1, arr1 = input().split()
n2, arr2 = input().split()

n1 = int(n1)
n2 = int(n2)
arr1 = arr1.decode()
arr2 = arr2.decode()

# 将字符映射到评分表的下标
idx = {'A': 0, 'C': 1, 'G': 2, 'T': 3, '-': 4}

# 行、列顺序都是 A C G T -
score = [
    [ 5, -1, -2, -1, -3],
    [-1,  5, -3, -2, -4],
    [-2, -3,  5, -2, -2],
    [-1, -2, -2,  5, -1],
    [-3, -4, -2, -1,  0],  # 两个空位对应的得分不会被使用
]
#dp[i][j]表示第一个序列的前i个字符以及第二个序列的前j个字符对齐所能带来的最大收益
dp = [[0] * (n2 + 1) for _ in range(n1 + 1)]

# 第二个序列为空
for i in range(1, n1 + 1):
    x = idx[arr1[i - 1]]
    dp[i][0] = dp[i - 1][0] + score[x][4]

# 第一个序列为空
for j in range(1, n2 + 1):
    y = idx[arr2[j - 1]]
    dp[0][j] = dp[0][j - 1] + score[4][y]

for i in range(1, n1 + 1):
    for j in range(1, n2 + 1):
        x = idx[arr1[i - 1]]
        y = idx[arr2[j - 1]]
        dp[i][j] = max(
            dp[i - 1][j - 1] + score[x][y],
            dp[i - 1][j] + score[x][4],
            dp[i][j - 1] + score[4][y]
        )#最后的结果不可能是两个空列所以不考虑两个空列的情况
print(dp[n1][n2])
