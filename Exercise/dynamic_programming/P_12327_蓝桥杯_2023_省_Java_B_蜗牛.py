import sys
input = sys.stdin.buffer.readline

n = int(input())
x = [0] + list(map(int, input().split()))

a = [0] * (n + 1)
b = [0] * (n + 1)

for i in range(1, n):
    a[i], b[i + 1] = map(int, input().split())

INF = float("inf")
dp = [[INF] * 2 for _ in range(n + 1)]

# 到达第一根竹竿底部
dp[1][0] = x[1]

for i in range(2, n + 1):
    # 上一根竹竿的传送门出口到入口的爬行时间
    if a[i - 1] >= b[i - 1]:
        t = (a[i - 1] - b[i - 1]) / 0.7
    else:
        t = (b[i - 1] - a[i - 1]) / 1.3

    # 通过传送门到达第 i 根竹竿
    dp[i][1] = min(
        dp[i - 1][0] + a[i - 1] / 0.7,
        dp[i - 1][1] + t
    )

    # 到达第 i 根竹竿底部
    dp[i][0] = min(
        dp[i - 1][0] + x[i] - x[i - 1],
        dp[i][1] + b[i] / 1.3
    )

print(f"{dp[n][0]:.2f}")