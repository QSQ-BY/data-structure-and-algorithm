import sys
input = sys.stdin.buffer.readline

#使用递推的思路
#对于每一个插入的新元素n，他一定是最大的元素
#他插入任何一个位置总共会多贡献0,1,2.....n-1个逆序对
#使用的关闭数列求和，最后就是贡献2**n-1
#对比n-1情况下的每一个逆序对数k,最后的结果都是2**k*(2**n-1)
#所以dp[n]=(2**n-1)*dp[n-1]
n = int(input())
MOD = 10**9 + 7
ans = 1
power = 1
for i in range(1, n + 1):
    power = power * 2 % MOD
    ans = ans * (power - 1) % MOD
print(ans)

