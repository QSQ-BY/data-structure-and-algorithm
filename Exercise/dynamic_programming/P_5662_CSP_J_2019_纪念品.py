T, N, M = map(int, input().split())

P = [list(map(int, input().split())) for _ in range(T)]

for i in range(T - 1):

    # dp[j] 表示最多花 j 枚金币能获得的最大利润
    dp = [0] * (M + 1)

    # 枚举每一种纪念品
    for k in range(N):
        cost = P[i][k]
        profit = P[i + 1][k] - P[i][k]

        # 不考虑亏损或不赚钱的纪念品
        if profit <= 0:
            continue

        # 完全背包：正序遍历
        for j in range(cost, M + 1):
            dp[j] = max(dp[j], dp[j - cost] + profit)

    # 更新金币
    M += dp[M]

print(M)