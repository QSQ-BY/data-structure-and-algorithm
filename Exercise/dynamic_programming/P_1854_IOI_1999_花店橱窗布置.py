import sys
input = sys.stdin.buffer.readline
def read():
    return map(int,input().split())

n,m = read()
g = [[]for _ in range(n)]
for i in range(n):
    g[i] = list(read())
#整个排列的下标相对顺序一定要是从小到大
dp = [[float("-inf")] * (m)for _ in range(n)]
#dp[i][j]表示考虑前i种花，最后一种花选取的下标为j的情况下所有花能获得的总美观度的最大值
dp[0] = g[0]#第一行的花只能选取他自身，就等于自身的美观度
path = [[-1] * m for _ in range(n)]#建立路径前驱数组
#定义path[i][j] = pre表示第i束花放在花瓶j的时候，这个最优方案种上一束花放在花瓶pre
#第i朵花能选取的最小的花的位置是i，最大的位置是m-i，因为要给后面的花留位置
for i in range(1,n):
    for j in range(i,m):
        #前面一朵花最后的位置不可能小于i-1,不可能大于j
        for pre in range(i-1,j):
            value = dp[i - 1][pre] + g[i][j]
            if value > dp[i][j]:
                dp[i][j] = value
                path[i][j] = pre
ans = max(dp[n-1])
#找到最后一束花所在的花瓶下标
last = dp[n-1].index(ans)

positions = [0]*(n)
#顺着last沿着路径向上找过去
for i in range(n-1,-1,-1):
    positions[i] = last + 1
    if(i > 0):
        last = path[i][last]#找到上一束花的位置
print(ans)
print(*positions)
