""" 题目描述
楼梯有 N 阶，上楼可以一步上一阶，也可以一步上二阶。

编一个程序，计算共有多少种不同的走法。

输入格式
一个数字，楼梯数。

输出格式
输出走的方式总数。

输入输出样例
输入 #1复制

4
输出 #1复制

5
说明/提示
对于 60% 的数据，N≤50；
对于 100% 的数据，1≤N≤5000。 """
import sys
input = sys.stdin.buffer.readline
n= int(input())
dp = [0]*(n+1)
#dp[n]表示上到n个楼梯一共有多少种走法
#只差一楼的时候只能走一个楼梯
#差两楼的时候可以直接走两个楼梯
#dp[n] = dp[n-1] +dp[n-2]
dp[0] = 1
if(n>=1):
    dp[1] = 1
if(n>= 2):
    dp[2] = 2
for i in range(3,n+1):
    dp[i] = dp[i-1] + dp[i-2]

print(dp[n])