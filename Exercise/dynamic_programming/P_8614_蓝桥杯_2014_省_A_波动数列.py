""" 题目描述
观察这个数列：

1,3,0,2,−1,1,−2,⋯。

这个数列中后一项总是比前一项增加 2 或者减少 3。

栋栋对这种数列很好奇，他想知道长度为 n 和为 s 而且后一项总是比前一项增加 a 或者减少 b 的整数数列可能有多少种呢？

输入格式
输入的第一行包含四个整数 n,s,a,b，含义如前面说述。

输出格式
输出一行，包含一个整数，表示满足条件的方案数。由于这个数很大，请输出方案数除以 100000007 的余数。

输入输出样例
输入 #1复制

4 10 2 3
输出 #1复制

2
说明/提示
【样例说明】

这两个数列分别是 2 4 1 3 和 7 4 1 -2。

【数据规模与约定】

对于 10% 的数据，1≤n≤5，0≤s≤5，1≤a,b≤5；

对于 30% 的数据，1≤n≤30，0≤s≤30，1≤a,b≤30；

对于 50% 的数据，1≤n≤50，0≤s≤50，1≤a,b≤50；

对于 70% 的数据，1≤n≤100，0≤s≤500，1≤a,b≤50；

对于 100% 的数据，1≤n≤1000，−10 
9
 ≤s≤10 
9
 ，1≤a,b≤10 
6
 。

时限 1 秒, 256M。蓝桥杯 2014 年第五届省赛 """
import sys
input = sys.stdin.buffer.readline
def read():
    return map(int,input().split())


#长度为N,和为s，的情况下，下一位总是比前一位增加a,或者减少b
n, s, a, b = read()
MOD = 100000007

# n 个数共有 n-1 个相邻差值
# 第一维：已经确定的差值个数，范围为 0 到 n-1
# 第二维：加权和模 n 的余数
# dp[i][r] 表示：确定前 i 个相邻差值后，加权和除以 n 的余数为 r 的方案数。
dp = [[0] * n for _ in range(n)]
dp[0][0] = 1
for i in range(1, n):
    weight = n - i
    for r in range(n):
        # 第 i 个差值选择 +a
        nxt = (r + weight * a) % n
        dp[i][nxt] = (
            dp[i][nxt] + dp[i - 1][r]
        ) % MOD
        # 第 i 个差值选择 -b
        nxt = (r - weight * b) % n
        dp[i][nxt] = (
            dp[i][nxt] + dp[i - 1][r]
        ) % MOD

print(dp[n - 1][s % n])
