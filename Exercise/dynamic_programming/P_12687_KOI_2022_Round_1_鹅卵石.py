import sys
input = sys.stdin.buffer.readline
def read():
    return map(int,input().split())
n = int(input())
arr = list(read())
# dp[i] 表示拿走前 i 堆鹅卵石所需的最少操作次数
dp = [0] * (n + 1)
for i in range(1, n + 1):
    # 最后一堆单独拿走
    dp[i] = dp[i - 1] + 1

    # 从右向左枚举最后一个连续处理的区间
    remaining = arr[i - 1]
    for j in range(i - 2, -1, -1):
        # 清空右边的剩余量后，当前这一堆还剩多少
        remaining = arr[j] - remaining
        if remaining < 0:
            break
        if remaining == 0:
            # 区间 [j, i-1] 可用至多 i-j-1 次相邻操作清空
            dp[i] = min(dp[i], dp[j] + i - j - 1)

print(dp[n])
