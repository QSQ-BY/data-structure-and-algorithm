""" 题目描述
机器猫要在电脑前打字。一共需要打 n 个字，但现在文档里只有一个字。

机器猫有两种操作可以做。假设现在已经有 x 个字，机器猫可以选择：

往文档最后加一个字。字数变成 x+1。
把文档复制粘贴一遍。字数变成 2x。
问机器猫至少需要多少次操作，才能得到恰好 n 个字。

输入格式
仅一行，一个正整数 n。

输出格式
仅一行，一个正整数，表示最少操作次数。

输入输出样例
输入 #1复制

16
输出 #1复制

4
输入 #2复制

5
输出 #2复制

3
说明/提示
样例解释
样例数据 1，1→2→4→8→16，共 4 步。

样例数据 2，1→2→4→5，共 3 步。

数据规模与约定
对于 100% 的数据，n≤10 
6
 。 """
#从一开始进行后续操作
#dp[n] = min(dp[n//2]+1,dp[n-1]+1)
import sys
input = sys.stdin.buffer.readline
n = int(input())
dp = [float("inf")]*(n+1)
dp[1] = 0
if(n >= 2):
    dp[2] = 1
else:
    print(0)
    sys.exit()
for i in range(3,n+1):
    dp[i] = min(dp[i],dp[i-1]+1)
    if(i % 2 == 0):
        dp[i] = min(dp[i],dp[i//2]+1)
print(dp[n])