import sys
from collections import deque
input = sys.stdin.buffer.readline
def read():
    return map(int,input().split())
#直接枚举下一个点在哪,时间复杂度能到n方
def solution1():
    n,l,r = read()
    arr = list(read())
    #dp[i]表示跳到i点的时候能获得的最大冰冻指数
    dp = [float("-inf")]*(n+1)
    dp[0] = 0
    for i in range(n+1):
        #考虑当前位置能够跳到哪里
        for next in range(min(i+l,n+1),min(i+r+1,n+1)):
            dp[next] = max(dp[i] + arr[next],dp[next])
    print(max(dp[n-r+1:]))

#使用单调队列进行优化，寻找每一个下个区间内的最大值
#时间复杂度能到n
def solution2():
    n,l,r = read()
    arr = list(read())
    dp = [float("-inf")]*(n+1)
    dp[0] = 0

    #保存下标，对应的dp值从队首到队尾呈递减趋势，对头是对应区间内的最大值
    q = deque()
    for i in range(1,n+1):
        #考虑当前位置能够从哪里转移过来
        #当前前驱区间:[i-r,i-l]
        #进入新区间的位置
        #需要寻找在j属于[i-r,i-l]这一段区间内最大的dp[j]
        k = i-l
        #k要合法且不能是不可达状态
        if(k>=0 and dp[k] != float("-inf")):
            #正常的单调队列更新
            while q and dp[q[-1]] <= dp[k]:
                q.pop()
            q.append(k)
        #处理对头超过范围的元素
        while q and q[0] < i-r:
            q.popleft()
        #队首就是当前合法区间内的最佳状态
        if(q):
            dp[i] = dp[q[0]] + arr[i]

    print(max(dp[n-r+1:]))


