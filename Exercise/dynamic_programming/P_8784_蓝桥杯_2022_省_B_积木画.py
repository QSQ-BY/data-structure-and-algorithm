""" 题目描述
小明最近迷上了积木画，有这么两种类型的积木，分别为 I 型（大小为 2 个单位面积) 和 L 型 (大小为 3 个单位面积):

I 型积木

同时，小明有一块面积大小为 2×N 的画布，画布由 2×N 个 1×1 区域构成。小明需要用以上两种积木将画布拼满，他想知道总共有多少种不同的方式? 积木可以任意旋转，且画布的方向固定。

输入格式
输入一个整数 N，表示画布大小。

输出格式
输出一个整数表示答案。由于答案可能很大，所以输出其对 1000000007（即 10 
9
 +7）取模后的值。

输入输出样例
输入 #1复制

3
输出 #1复制

5
说明/提示
【样例说明】

五种情况如下图所示, 颜色只是为了标识不同的积木: 

【评测用例规模与约定】

对于所有测试用例，1≤N≤10 
7
 。

蓝桥杯 2022 省赛 B 组 G 题。 """
#增加辅助状态然后消去辅助状态
from array import array
MOD = 10**9 + 7
n = int(input())
f = array('I', [0]) * (n + 1)
g = array('I', [0]) * (n + 1)
# 初始化
f[0] = 1
f[1] = 1
g[1] = 0
# 动态规划
for i in range(2, n + 1):
    f[i] = (f[i-1] + f[i-2] + 2*g[i-1]) % MOD
    g[i] = (g[i-1] + f[i-2]) % MOD
print(f[n])
