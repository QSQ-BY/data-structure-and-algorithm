#if(arr[j] > arr[i]):
#    dp[i][j][1] += dp[i][j-1][0]

arr = list(read())
MOD = 19650827
dp = [[[0]*2 for _ in range(n)]for _ in range(n)]
#初始化dp[i][i]，单元素只有一种方案，约定归到状态0以免重复计数
for i in range(n):
    dp[i][i] = [1,0]
for length in range(2,n+1):
    for j in range(length-1,n):#枚举右边界
        i = j+1 - length#计算出左边界
        if(arr[i] < arr[i+1]):
            dp[i][j][0] += dp[i+1][j][0]
        if(arr[i] < arr[j]):
            dp[i][j][0] += dp[i+1][j][1]
        if(arr[j] > arr[j-1]):
            dp[i][j][1] += dp[i][j-1][1]
        if(arr[j] > arr[i]):
            dp[i][j][1] += dp[i][j-1][0]
        dp[i][j][0] %= MOD
        dp[i][j][1] %= MOD

#最后的整个序列分为最后从左边插入和最后从右边插入
print((dp[0][n-1][0] + dp[0][n-1][1]) % MOD)
