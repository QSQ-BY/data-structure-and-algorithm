import sys
input = sys.stdin.buffer.readline
def read():
    return map(int,input().split())

n = int(input())
#dp[i][j][k]表示得到原序列的[i,j]闭区间的这一段序列，且最后一个插入的元素是左边还是右边的元素，一共有多少种方法
#k为0代表整个队列最后一个插入的元素是左边的元素，k为1表示整个序列最后一个插入的元素是最右边的元素
#[i,j]这一段的序列只能由，[i+1,j]或者[i,j-1]这两段序列得到
#dp[i][j][0],把当前数字插入到整个队列的最左边，说明当前数字一定要比上一个数字要小,以此类推
#if(arr[i] < arr[i+1]):
