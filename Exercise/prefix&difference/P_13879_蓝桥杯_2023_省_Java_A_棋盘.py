#二维差分数组
import sys
input = sys.stdin.buffer.readline
def read():
    return map(int,input().split())

n,m = read()
# 二维差分数组，多开一圈防止 x2+1 / y2+1 越界
d = [[0]*(n+2) for _ in range(n+2)]
for _ in range(m):
    x1,y1,x2,y2 = read()
    d[x1][y1] += 1
    d[x1][y2+1] -= 1
    d[x2+1][y1] -= 1
    d[x2+1][y2+1] += 1

# 二维前缀和：还原出每个格子被翻转的次数
for i in range(1,n+1):
    for j in range(1,n+1):
        d[i][j] += d[i-1][j] + d[i][j-1] - d[i-1][j-1]

# 最后再判断奇偶：奇数次是黑(1)，偶数次是白(0)
for i in range(1,n+1):
    print(''.join('1' if d[i][j] % 2 else '0' for j in range(1,n+1)))
